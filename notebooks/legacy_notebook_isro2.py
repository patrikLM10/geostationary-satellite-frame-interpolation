def denormalize(norm, lo=0.0, hi=200.0):
    return (norm * (hi - lo) + lo).astype(np.float32)

def _fill_nans_local_median(arr):
    arr = arr.astype(np.float32)
    if np.isnan(arr).any():
        med = scipy.ndimage.median_filter(np.nan_to_num(arr, nan=np.nanmedian(arr)), size=3)
        arr = np.where(np.isnan(arr), med, arr)
        arr = np.nan_to_num(arr, nan=np.nanmedian(arr))
    return arr

def load_frame(nc_path):
    with xr.open_dataset(nc_path) as ds:
        rad = ds["Rad"].values.astype(np.float32)

    rad = _fill_nans_local_median(rad)

    H, W = rad.shape
    ps = 512
    if H >= ps and W >= ps:
        cy, cx = H // 2, W // 2
        rad = rad[cy - ps // 2: cy + ps // 2, cx - ps // 2: cx + ps // 2]

    return rad.astype(np.float32)

