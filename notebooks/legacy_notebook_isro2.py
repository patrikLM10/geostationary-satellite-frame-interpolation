class GOESTripletDataset(Dataset):
    def __init__(self, triplets, patch_size=256, patches_per_triplet=4):
        self.triplets = triplets
        self.patch_size = patch_size
        self.items = [t for t in self.triplets for _ in range(patches_per_triplet)]

    def __len__(self):
        return len(self.items)

    def __getitem__(self, idx):
        paths = self.items[idx]
        r0, r10, r20 = load_triplet(*paths)

        H, W = r0.shape
        ps = self.patch_size

        if H <= ps or W <= ps:
            crop0, crop10, crop20 = r0, r10, r20
        else:
            y = np.random.randint(0, H - ps)
            x = np.random.randint(0, W - ps)
            crop0 = r0[y:y+ps, x:x+ps]
            crop10 = r10[y:y+ps, x:x+ps]
            crop20 = r20[y:y+ps, x:x+ps]

        if np.random.rand() > 0.5:
            crop0 = np.fliplr(crop0)
            crop10 = np.fliplr(crop10)
            crop20 = np.fliplr(crop20)

        t0 = torch.from_numpy(crop0.copy()).unsqueeze(0).float()
        t10 = torch.from_numpy(crop10.copy()).unsqueeze(0).float()
        t20 = torch.from_numpy(crop20.copy()).unsqueeze(0).float()

        return {'frame0': t0, 'target': t10, 'frame1': t20}

def train_one_epoch(raft, zmap, unet, loader, optimizer, scaler, dev):
    unet.train()
    zmap.train()
    raft.eval()

    epoch_loss = 0.0
    epoch_ssim = 0.0
    criterion = CompositeLoss()

    pbar = tqdm(loader, desc="Training", leave=False)
    for batch in pbar:
        f0 = batch['frame0'].to(dev)
        f1 = batch['frame1'].to(dev)
        tgt = batch['target'].to(dev)

        optimizer.zero_grad()

        with torch.no_grad():
            f_fwd, f_bwd = raft(f0, f1), raft(f1, f0)
            t = 0.5
            flow_fwd = f_fwd * t
            flow_bwd = f_bwd * (1 - t)
            mask_fwd, mask_bwd = occlusion_masks(flow_fwd, flow_bwd)

        with torch.amp.autocast(device_type=dev, enabled=(dev=='cuda')):
            z0 = zmap(f0)
            z1 = zmap(f1)
            w0, w1, mf, mb = bidirectional_splat(f0, f1, flow_fwd, flow_bwd, z0, z1, mask_fwd, mask_bwd)
            unet_in = make_unet_input(w0, w1, flow_fwd, flow_bwd, mf, mb)

            # --- Residual Synthesis ---
            unet_out = unet(unet_in)
            base_blend = 0.5 * w0 + 0.5 * w1
            pred = torch.clamp(base_blend + (unet_out - 0.5), 0.0, 1.0)

            loss = criterion(pred, tgt)

        if dev == 'cuda':
            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(list(unet.parameters()) + list(zmap.parameters()), max_norm=1.0)
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()
            torch.nn.utils.clip_grad_norm_(list(unet.parameters()) + list(zmap.parameters()), max_norm=1.0)
            optimizer.step()

        epoch_loss += loss.item()
        with torch.no_grad():
            s_val = piq.ssim(pred.float(), tgt.float(), data_range=1.0).item()
            epoch_ssim += s_val

        pbar.set_postfix({'loss': f"{loss.item():.4f}", 'ssim': f"{s_val:.4f}"})

    return epoch_loss / len(loader), epoch_ssim / len(loader)

