import scipy.ndimage

def normalize(rad, lo=0.0, hi=200.0):
    return np.clip((rad - lo) / (hi - lo), 0.0, 1.0).astype(np.float32)

def denormalize(norm, lo=0.0, hi=200.0):
    return (norm * (hi - lo) + lo).astype(np.float32)

def load_frame(nc_path):
    with xr.open_dataset(nc_path) as ds:
        rad = ds["Rad"].values

    H, W = rad.shape
    cy, cx = H//2, W//2
    # Extract 512x512 central patch
    rad_crop = rad[cy-256:cy+256, cx-256:cx+256]

    if np.isnan(rad_crop).any():
        med = scipy.ndimage.median_filter(rad_crop, size=3)
        rad_crop = np.where(np.isnan(rad_crop), med, rad_crop)
        rad_crop = np.nan_to_num(rad_crop, nan=np.nanmedian(rad_crop))

    return rad_crop.astype(np.float32)

def load_triplet(path_t0, path_t10, path_t20):
    r0 = load_frame(path_t0)
    r10 = load_frame(path_t10)
    r20 = load_frame(path_t20)
    return normalize(r0), normalize(r10), normalize(r20)

