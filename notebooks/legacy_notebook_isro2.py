def warp_flow(frame_tensor, flow_tensor):
    B, C, H, W = frame_tensor.size()
    xx   = torch.arange(0, W).view(1, -1).repeat(H, 1)
    yy   = torch.arange(0, H).view(-1, 1).repeat(1, W)
    xx   = xx.view(1, 1, H, W).repeat(B, 1, 1, 1)
    yy   = yy.view(1, 1, H, W).repeat(B, 1, 1, 1)
    grid = torch.cat((xx, yy), 1).float().to(frame_tensor.device)
    vgrid = grid + flow_tensor
    vgrid[:, 0] = 2.0 * vgrid[:, 0].clone() / max(W - 1, 1) - 1.0
    vgrid[:, 1] = 2.0 * vgrid[:, 1].clone() / max(H - 1, 1) - 1.0
    vgrid = vgrid.permute(0, 2, 3, 1)
    return F.grid_sample(frame_tensor, vgrid, align_corners=True,
                         mode='bilinear', padding_mode='border')

def occlusion_masks(flow_fwd_t, flow_bwd_t, threshold=1.0):
    warped_bwd = warp_flow(flow_bwd_t, flow_fwd_t)
    err_fwd    = torch.norm(flow_fwd_t + warped_bwd, dim=1, keepdim=True)
    mask_fwd   = (err_fwd < threshold).float()
    warped_fwd = warp_flow(flow_fwd_t, flow_bwd_t)
    err_bwd    = torch.norm(flow_bwd_t + warped_fwd, dim=1, keepdim=True)
    mask_bwd   = (err_bwd < threshold).float()
    return mask_fwd, mask_bwd

