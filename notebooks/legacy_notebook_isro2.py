def make_unet_input(w0, w1, ff, fb, mf, mb):
    B, _, H, W = w0.shape
    ff_norm = ff / max(H, W)
    fb_norm = fb / max(H, W)
    return torch.cat([w0, w1, ff_norm, fb_norm, mf, mb], dim=1)

class CompositeLoss(nn.Module):
    def __init__(self):
        super().__init__()
        self.l1 = nn.L1Loss()

    def forward(self, pred, target):
        loss_l1 = self.l1(pred, target)
        loss_ssim = 1.0 - piq.ssim(pred, target, data_range=1.0)
        return 0.2 * loss_l1 + 0.8 * loss_ssim

