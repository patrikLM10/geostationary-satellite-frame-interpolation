class SatelliteRAFT(nn.Module):
    def __init__(self):
        super().__init__()
        try:
            from torchvision.models.optical_flow import raft_small, Raft_Small_Weights
            weights       = Raft_Small_Weights.DEFAULT
            self.model    = raft_small(weights=weights, progress=False).to(device).eval()
            self.transforms = weights.transforms()
            self.use_raft = True
        except Exception as e:
            print(f"Warning: RAFT load failed ({e}). Using Farneback fallback.")
            self.use_raft = False

    def forward(self, f0, f1):
        B, C, H, W = f0.shape
        if not self.use_raft:
            flows = []
            for i in range(B):
                img0 = (f0[i, 0].cpu().numpy() * 255).astype(np.uint8)
                img1 = (f1[i, 0].cpu().numpy() * 255).astype(np.uint8)
                flow = cv2.calcOpticalFlowFarneback(img0, img1, None, 0.5, 3, 15, 3, 5, 1.2, 0)
                flows.append(torch.from_numpy(flow).permute(2, 0, 1))
            return torch.stack(flows).to(device)

        f0_rgb = f0.repeat(1, 3, 1, 1) * 255.0
        f1_rgb = f1.repeat(1, 3, 1, 1) * 255.0
        pad_h  = (8 - H % 8) % 8
        pad_w  = (8 - W % 8) % 8
        if pad_h > 0 or pad_w > 0:
            f0_rgb = torch.nn.functional.pad(f0_rgb, (0, pad_w, 0, pad_h))
            f1_rgb = torch.nn.functional.pad(f1_rgb, (0, pad_w, 0, pad_h))
        f0_t, f1_t = self.transforms(f0_rgb, f1_rgb)
        with torch.no_grad():
            flow = self.model(f0_t, f1_t)[-1]
        return flow[:, :, :H, :W]

def get_bidirectional_flow(model, frame0_np, frame1_np, t=0.5, dev=device):
    t0 = torch.from_numpy(frame0_np).unsqueeze(0).unsqueeze(0).to(dev)
    t1 = torch.from_numpy(frame1_np).unsqueeze(0).unsqueeze(0).to(dev)
    with torch.no_grad():
        f_fwd = model(t0, t1)
        f_bwd = model(t1, t0)
    return f_fwd * t, f_bwd * (1 - t)

