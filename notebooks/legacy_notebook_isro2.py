def train_one_epoch(raft, zmap, unet, loader, optimizer, scaler, dev):
    unet.train(); zmap.train(); raft.eval()
    epoch_loss = epoch_ssim = 0.0
    criterion  = CompositeLoss()
    pbar       = tqdm(loader, desc="Training", leave=False)

    for batch in pbar:
        f0  = batch['frame0'].to(dev)
        f1  = batch['frame1'].to(dev)
        tgt = batch['target'].to(dev)
        optimizer.zero_grad()

        with torch.no_grad():
            flow_fwd_b = raft(f0, f1) * 0.5
            flow_bwd_b = raft(f1, f0) * 0.5
            mf_b, mb_b = occlusion_masks(flow_fwd_b, flow_bwd_b)

        with torch.amp.autocast(device_type=dev, enabled=(dev == 'cuda')):
            z0_b = zmap(f0); z1_b = zmap(f1)
            w0_b, w1_b, mf_b2, mb_b2 = bidirectional_splat(
                f0, f1, flow_fwd_b, flow_bwd_b, z0_b, z1_b, mf_b, mb_b)
            unet_in  = make_unet_input(w0_b, w1_b, flow_fwd_b, flow_bwd_b, mf_b2, mb_b2)
            unet_out = unet(unet_in)
            base     = 0.5 * w0_b + 0.5 * w1_b
            pred     = torch.clamp(base + (unet_out - 0.5), 0.0, 1.0)
            loss     = criterion(pred, tgt)

        if dev == 'cuda':
            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(
                list(unet.parameters()) + list(zmap.parameters()), 1.0)
            scaler.step(optimizer); scaler.update()
        else:
            loss.backward()
            torch.nn.utils.clip_grad_norm_(
                list(unet.parameters()) + list(zmap.parameters()), 1.0)
            optimizer.step()

        epoch_loss += loss.item()
        with torch.no_grad():
            s = piq.ssim(pred.float(), tgt.float(), data_range=1.0).item()
        epoch_ssim += s
        pbar.set_postfix({'loss': f"{loss.item():.4f}", 'ssim': f"{s:.4f}"})

    return epoch_loss / len(loader), epoch_ssim / len(loader)

