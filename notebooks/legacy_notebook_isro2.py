def interpolate(norm0, norm1, raft, zmap, unet, t=0.5, dev=device):
    f0 = torch.from_numpy(norm0).unsqueeze(0).unsqueeze(0).to(dev)
    f1 = torch.from_numpy(norm1).unsqueeze(0).unsqueeze(0).to(dev)

